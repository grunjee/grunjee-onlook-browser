import fs from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
import { readBakeryBuild } from './bakery-build.mjs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'../..');
const read=(f)=>fs.readFileSync(path.join(here,f),'utf8');
const model=read('model.mjs'),render=read('render.mjs');
const idSource=fs.readFileSync(path.join(root,'apps/web/preload/script/helpers/ids.ts'),'utf8');
const constants=fs.readFileSync(path.join(root,'packages/constants/src/editor.ts'),'utf8');
const getId=idSource.match(/export function getOid\(node: HTMLElement\): string \| null \{([\s\S]*?)\n\}/)?.[1];
const attr=constants.match(/DATA_ONLOOK_ID = '([^']+)'/)?.[1];
if(!getId||attr!=='data-oid')throw new Error('Verify the Onlook selection API before building.');
const frame='function getOid(node){'+getId.replace('EditorAttributes.DATA_ONLOOK_ID',JSON.stringify(attr))+'}\n'+read('web/frame.js');
const mark='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 40 40"><rect width="40" height="40" rx="9" fill="#194b3d"/><g fill="none" stroke="#e4f5e4" stroke-width="2.3" stroke-linecap="round" stroke-linejoin="round"><path d="M16 7h8m-7 0v11l-8 12q-1 3 2 3h18q3 0 2-3l-8-12V7M13 25h14"/></g></svg>';
const assets={bakery:readBakeryBuild(),index:read('web/index.html'),css:read('web/desk.css'),js:read('web/desk.js'),pageCss:read('web/page.css'),frame,mark,model,render};
const strip=s=>s.replace(/^export /gm,'');
const parseSource=fs.readFileSync(path.join(root,'packages/parser/src/parse.ts'),'utf8');
const parseOptions=parseSource.match(/return parse\(content, (\{[\s\S]*?\n        \})\);/)?.[1];
if(!parseOptions)throw new Error('Verify upstream parser options.');
const vendor=fs.readFileSync(require.resolve('@babel/parser'),'utf8').split('//# sourceMappingURL')[0];
const parser='const babel=(()=>{const exports={};'+vendor+';return exports})()';
const getAst='function getAstFromContent(content){try{return babel.parse(content,'+parseOptions+')}catch{return null}}';
const output=[strip(model),strip(render),parser,getAst,read('source-tools.mjs'),read('bakery.mjs'),'const ASSETS='+JSON.stringify(assets)+';',read('worker.mjs')].join('\n');
fs.mkdirSync(path.join(root,'dist/server'),{recursive:true});
fs.writeFileSync(path.join(root,'dist/server/index.js'),output);
console.log('Built the Grunjee browser workspace from the pinned Onlook source.');
